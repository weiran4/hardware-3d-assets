import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';

for(const width of [1280,390])test('P39 DI uses a detached exact Siemens PLC exterior '+width,async({page})=>{
 test.setTimeout(90000);
 await page.setViewportSize({width,height:950});
 await page.goto('./#rtds-presentation-39');
 const lab=page.locator('.lightdio-bench'),stage=lab.locator('.lightdio-stage');
 const plc=lab.locator('button[data-device-focus="plc"]');
 const mode=lab.locator('[data-lightdio="mode"]');
 await lab.scrollIntoViewIfNeeded();
 await expect(stage).toHaveAttribute('data-loaded','true');
 await expect(stage).toHaveAttribute('data-plc-model','siemens-s7-1200-cpu-1212c');
 await expect(stage).toHaveAttribute('data-photo-status','ready');
 await expect(stage).toHaveAttribute('data-device-representations',/"plc":"photo"/);
 await expect(lab.getByRole('link',{name:/Siemens.*实物/})).toHaveAttribute('href',/6es7212-1ae40-0xb0/i);
 await expect(lab.locator('.lightbench-photo-status[role=status]')).toContainText('不对应 PLC 实体端子');
 await lab.locator('[data-lightdio-connect]').click();
 await expect(lab).toHaveAttribute('data-status','ready');
 await expect(lab.locator('.lightdio-reading')).toContainText('1 · 24 V');
 const readLinks=async()=>JSON.parse(await stage.getAttribute('data-wire-endpoints'));
 const linked=await readLinks();
 expect(linked.flatMap(({a,b})=>[a,b]).filter(key=>key.startsWith('E.')).sort()).toEqual(['E.return','E.signal']);
 await expect(stage).toHaveAttribute('data-wires-visible','true');
 await mkdir('screenshots',{recursive:true});
 await stage.screenshot({path:'screenshots/p39-siemens-plc-bench-'+width+'.png'});
 await plc.focus();
 await page.keyboard.press('Enter');
 await expect(plc).toHaveAttribute('aria-pressed','true');
 await expect(stage).toHaveAttribute('data-focused-device','plc');
 await expect(stage).toHaveAttribute('data-wires-visible','false');
 await expect(stage).toHaveAttribute('aria-label','Siemens CPU 1212C 实物外观三维近看');
 await expect(lab.locator('[data-lightdio-play]')).toBeDisabled();
 await expect(lab.locator('[data-lightdio-step]')).toBeDisabled();
 expect(await readLinks()).toEqual(linked);
 await expect.poll(async()=>Number(await stage.getAttribute('data-triangles'))).toBeGreaterThan(400);
 await stage.screenshot({path:'screenshots/p39-siemens-plc-exterior-'+width+'.png'});
 await lab.locator('[data-lightdio="high"]').evaluate(el=>{el.checked=false;el.dispatchEvent(new Event('change',{bubbles:true}));});
 await expect(lab.locator('.lightdio-reading')).toContainText('0 · 0 V');
 await expect(stage).toHaveAttribute('data-focused-device','plc');
 await expect(stage).toHaveAttribute('data-wires-visible','false');
 await expect(plc).toBeFocused();
 await lab.getByRole('button',{name:'查看全部',exact:true}).click();
 await expect(stage).toHaveAttribute('data-focused-device','all');
 await expect(stage).toHaveAttribute('data-wires-visible','true');
 await expect(lab.locator('[data-lightdio-step]')).toBeEnabled();
 expect(await readLinks()).toEqual(linked);
 await mode.selectOption('do');
 await expect(stage).not.toHaveAttribute('data-plc-model','siemens-s7-1200-cpu-1212c');
 await expect(plc).toHaveCount(0);
 await mode.selectOption('di');
 await expect(stage).toHaveAttribute('data-plc-model','siemens-s7-1200-cpu-1212c');
 await stage.locator('canvas').evaluate(c=>c.dispatchEvent(new Event('webglcontextlost',{cancelable:true})));
 await expect(stage).toHaveAttribute('data-loaded','false');
 await expect(plc).toHaveCount(0);
 await lab.locator('[data-lightdio-retry]').click();
 await expect(stage).toHaveAttribute('data-loaded','true');
 await expect(stage).toHaveAttribute('data-plc-model','siemens-s7-1200-cpu-1212c');
 await expect(stage.locator('canvas')).toHaveCount(1);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
