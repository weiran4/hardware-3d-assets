import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';

for (const width of [1280,390]) test('P39 AO models the DS1054Z separately from logical endpoints at '+width, async({page})=>{
 test.setTimeout(90000);
 await page.setViewportSize({width,height:900});
 await page.goto('./#rtds-presentation-39');
 const lab=page.locator('.lightbench-bench'),stage=lab.locator('.lightbench-stage');
 const scope=lab.getByRole('button',{name:/放大.*DS1054Z/});
 await expect(stage).toHaveAttribute('data-loaded','true');
 await expect(stage).toHaveAttribute('data-scope-model','rigol-ds1054z',{timeout:3000});
 await expect(stage).toHaveAttribute('data-photo-status','ready');
 await expect(lab.getByRole('link',{name:/DS1054Z.*实物/})).toHaveAttribute('href','https://cdn-reichelt.de/bilder/web/xxl_ws/D100/DS1054Z_01.png');
 const status=lab.locator('.lightbench-photo-status[role="status"]');
 await expect(status).toContainText('不对应示波器实体端口');
 await expect(status).toContainText('等效负载仅用于仿真计算');
 await lab.locator('[data-lightbench-connect]').click();
 await expect(lab).toHaveAttribute('data-status','ready');
 await expect(lab.locator('.lightbench-reading')).toContainText('5.00mA');
 await expect(stage).toHaveAttribute('data-wires','5');
 const endpoints=JSON.parse(await stage.getAttribute('data-wire-endpoints'));
 expect(endpoints.flatMap(({a,b})=>[a,b]).filter(key=>key.startsWith('E.')).sort()).toEqual(['E.return','E.signal']);
 await mkdir('screenshots',{recursive:true});
 await stage.screenshot({path:'screenshots/p39-ds1054z-bench-'+width+'.png'});
 await scope.focus();
 await page.keyboard.press('Enter');
 await expect(stage).toHaveAttribute('data-focused-device','scope');
 await expect(scope).toHaveAttribute('aria-pressed','true');
 await expect.poll(async()=>Number(await stage.getAttribute('data-triangles'))).toBeGreaterThan(4000);
 await stage.screenshot({path:'screenshots/p39-ds1054z-exterior-'+width+'.png'});
 await lab.locator('[data-lightbench="voltage"]').evaluate(el=>{el.value='2';el.dispatchEvent(new Event('change',{bubbles:true}));});
 await expect(stage).toHaveAttribute('data-focused-device','scope');
 await expect(scope).toBeFocused();
 await lab.getByRole('button',{name:'查看全部',exact:true}).click();
 await expect(stage).toHaveAttribute('data-focused-device','all');
 const mode=lab.locator('[data-lightbench="mode"]');
 await mode.selectOption('ai');
 await expect(stage).not.toHaveAttribute('data-scope-model','rigol-ds1054z');
 await expect(scope).toHaveCount(0);
 await mode.selectOption('ao');
 await expect(stage).toHaveAttribute('data-scope-model','rigol-ds1054z');
 await expect(stage.locator('canvas')).toHaveCount(1);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
