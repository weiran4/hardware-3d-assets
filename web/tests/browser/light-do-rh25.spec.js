import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';

for(const width of [1280,390])test(`P39 DO detached exact Vishay Dale RH-25 exterior ${width}`,async({page})=>{
 test.setTimeout(90000);await page.setViewportSize({width,height:950});await page.goto('./#rtds-presentation-39');
 const lab=page.locator('.lightdio-bench'),stage=lab.locator('.lightdio-stage'),control=k=>lab.locator(`[data-lightdio="${k}"]`);
 const rh=lab.locator('button[data-device-focus="rh25"]'),uno=lab.locator('button[data-device-focus="uno"]'),play=lab.locator('[data-lightdio-play]'),step=lab.locator('[data-lightdio-step]');
 await lab.scrollIntoViewIfNeeded();await expect(stage).toHaveAttribute('data-loaded','true');await expect(rh).toHaveCount(0);
 await control('mode').selectOption('do');await stage.scrollIntoViewIfNeeded();
 await expect(stage).toHaveAttribute('data-rh25-model','vishay-dale-rh25');
 await expect(stage).toHaveAttribute('data-device-representations',/"rh25":"photo"/);
 await expect(stage).toHaveAttribute('data-uno-model','phoenix-uno-ps-2902991');
 await expect(lab.getByRole('link',{name:/RH-25.*实物/})).toHaveAttribute('href',/ebayimg\.com/);
 await expect(lab.locator('.lightbench-photo-status[role=status]')).toContainText(/RH-25.*未接线.*阻值/);
 await lab.locator('[data-lightdio-connect]').click();await stage.scrollIntoViewIfNeeded();
 await expect(lab).toHaveAttribute('data-status','ready');await expect(lab.locator('.lightdio-reading')).toContainText('输出驱动 · 24 V');
 const endpoints=async()=>JSON.parse(await stage.getAttribute('data-wire-endpoints'));
 await expect.poll(async()=>(await endpoints()).length).toBe(8);
 const old=await endpoints();
 const xyz=(key)=>{const link=old.find(({a,b})=>a===key||b===key);return (link.a===key?link.start:link.end).map(n=>Number(n.toFixed(6)));};
 expect(xyz('E.signal')).toEqual(width===390?[-.055,-.36,.10]:[.305,.04,.10]);
 expect(xyz('E.return')).toEqual(width===390?[.055,-.36,.10]:[.415,.04,.10]);
 const qa=process.env.LIGHT_RH25_QA_DIR;
 if(qa){await mkdir(qa,{recursive:true});await stage.screenshot({path:`${qa}/rh25-overview-${width}.png`});}
 await play.click();await expect(lab).toHaveAttribute('data-playing','true');
 await rh.focus();await page.keyboard.press('Enter');
 await expect(rh).toHaveAttribute('aria-pressed','true');
 await expect(stage).toHaveAttribute('data-focused-device','rh25');await expect(stage).toHaveAttribute('data-wires-visible','false');
 await expect(stage).toHaveAccessibleName(/RH-25.*未接线/);await expect(lab).toHaveAttribute('data-playing','false');
 await expect(play).toBeDisabled();await expect(step).toBeDisabled();expect(await endpoints()).toEqual(old);
 if(qa)await stage.screenshot({path:`${qa}/rh25-closeup-${width}.png`});
 await control('high').uncheck();await expect(lab.locator('.lightdio-reading')).toContainText('输出关闭');
 await expect(stage).toHaveAttribute('data-focused-device','rh25');expect(await endpoints()).toEqual(old);
 await uno.click();await expect(stage).toHaveAttribute('data-focused-device','uno');await expect(step).toBeDisabled();
 await lab.getByRole('button',{name:'查看全部',exact:true}).click();await expect(stage).toHaveAttribute('data-wires-visible','true');await expect(step).toBeEnabled();
 await rh.click();await control('mode').selectOption('di');await expect(rh).toHaveCount(0);await expect(stage).toHaveAttribute('data-focused-device','all');
 await control('mode').selectOption('do');await rh.click();
 await stage.locator('canvas').evaluate(c=>c.dispatchEvent(new Event('webglcontextlost',{cancelable:true})));await expect(rh).toHaveCount(0);
 await lab.locator('[data-lightdio-retry]').click();await expect(stage).toHaveAttribute('data-loaded','true');await expect(stage).toHaveAttribute('data-focused-device','all');await expect(stage.locator('canvas')).toHaveCount(1);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
