import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';
for(const width of [1280,390])test('P35 detached photographed gigabit switch '+width,async({page})=>{
 test.setTimeout(90000);await page.setViewportSize({width,height:1000});await page.goto('./#rtds-presentation-35');
 const b=page.locator('.udp-bench'),s=b.locator('.udp-stage'),top=b.locator('[data-udp=topology]'),a=k=>b.locator('[data-udp-inspect='+k+']');
 await expect(s).toHaveAttribute('data-loaded','true');
 await expect(a('switch-front')).toBeHidden();await top.selectOption('switch');
 await expect(a('switch-front')).toBeVisible({timeout:4000});
 await expect(s).toHaveAttribute('data-switch-model','moxa-eds-g308-rev-1-5-0');
 await expect(b.getByRole('link',{name:/EDS-G308.*实物/}).first()).toHaveAttribute('href',/vb-steuerungstechnik/);
 await b.locator('[data-udp-connect]').click();await b.locator('[data-udp-second]').click();
 await expect(s).toHaveAttribute('data-wires','2');const endpoints=()=>s.getAttribute('data-wire-endpoints');const old=await endpoints();
 const json=JSON.parse(old);expect(json.map(({a,b})=>[a,b])).toEqual([['N.udp','SW.in'],['SW.out','PC.nic']]);expect(json[0].end.map(n=>+n.toFixed(3))).toEqual(width===390?[.045,.12,.1]:[-.425,-.14,.1]);
 const dir=process.env.UDP_G308_CAPTURE;
 const cap=async k=>{if(dir){await mkdir(dir,{recursive:true});await s.screenshot({path:`${dir}/${width}-${k}.png`});}};
 await cap('overview');
 await b.locator('[data-udp-play]').click();await a('switch-front').focus();await page.keyboard.press('Enter');
 await expect(s).toHaveAccessibleName(/EDS-G308.*正面.*未接线/);await expect(s).toHaveAttribute('data-device-view','switch-front');
 await expect(b).toHaveAttribute('data-playing','false');await expect(s).toHaveAttribute('data-wires-visible','false');expect(await endpoints()).toBe(old);
 await expect(b.locator('[data-udp-port=udp]')).toBeHidden();await cap('front');
 await a('switch-rear').click();await expect(s).toHaveAccessibleName(/EDS-G308.*背面.*未接线/);await expect(s).toHaveAttribute('data-device-view','switch-rear');await cap('rear');
 await a('all').click();await expect(s).toHaveAttribute('data-wires-visible','true');expect(await endpoints()).toBe(old);
 await a('switch-front').click();await top.selectOption('direct');
 await expect(s).toHaveAttribute('data-device-view','all');await expect(a('switch-front')).toBeHidden();
 await expect(s).not.toHaveAttribute('data-switch-model',/.+/);await expect(s).toHaveAttribute('data-wires','0');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
