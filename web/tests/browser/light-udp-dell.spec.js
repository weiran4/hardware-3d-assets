import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';

for(const width of [1280,390])test('Light UDP Dell exterior is detached from both receiver routes '+width,async({page})=>{
 test.setTimeout(90000);await page.setViewportSize({width,height:1000});
 await page.goto('./#rtds-presentation-39');
 const b=page.locator('.lightudp-bench'),s=b.locator('.lightudp-stage'),t=b.locator('[data-lightudp="topology"]'),step=b.locator('[data-lightudp-step]'),play=b.locator('[data-lightudp-play]');
 const front=b.getByRole('button',{name:'看 Dell 正面'}),rear=b.getByRole('button',{name:'看 Dell 背板'}),all=b.getByRole('button',{name:'查看全部',exact:true});
 await s.scrollIntoViewIfNeeded();await expect(s).toHaveAttribute('data-photo-status','ready');
 await expect(s).toHaveAttribute('data-dell-model','dell-optiplex-7080-micro',{timeout:3500});
 await expect(b.getByRole('link',{name:/Dell OptiPlex 7080 Micro.*实物/})).toHaveAttribute('href',/11967\.1751156567/);
 await expect(b.locator('.lightbench-photo-status[role=status]')).toContainText(/Dell.*未接线.*PC NIC/);
 await b.locator('[data-lightudp-connect]').click();await s.scrollIntoViewIfNeeded();
 const points=async()=>JSON.parse(await s.getAttribute('data-wire-endpoints'));
 const compact=width===390,expectedEnd=compact?[.13,-.37,.055]:[.49,.03,.055],round=a=>a.map(n=>+n.toFixed(6));
 await expect(s).toHaveAttribute('data-wires','1');
 const direct=await points();
 expect(direct.map(({a,b,end})=>[a,b,round(end)])).toEqual([['L.eth','PC.eth',expectedEnd]]);
 const qa=process.env.LIGHT_DELL_QA_DIR;
 if(qa){await mkdir(qa,{recursive:true});await s.screenshot({path:`${qa}/direct-${width}.png`});}
 await play.click();await expect(b).toHaveAttribute('data-playing','true');
 await front.focus();await page.keyboard.press('Enter');
 await expect(front).toHaveAttribute('aria-pressed','true');
 await expect(s).toHaveAccessibleName(/Dell.*正面.*未接线/);
 await expect(s).toHaveAttribute('data-wires-visible','false');
 await expect(b).toHaveAttribute('data-playing','false');await expect(step).toBeDisabled();
 const count=await b.getAttribute('data-count');
 if(qa)await s.screenshot({path:`${qa}/front-${width}.png`});
 const frontZ=JSON.parse(await s.getAttribute('data-camera-position'))[2];
 await rear.click();await expect(rear).toHaveAttribute('aria-pressed','true');
 await expect(front).toHaveAttribute('aria-pressed','false');
 await expect(s).toHaveAccessibleName(/Dell.*背板.*未接线/);
 await expect.poll(async()=>JSON.parse(await s.getAttribute('data-camera-position'))[2]).toBeLessThan(frontZ-1);
 expect(await points()).toEqual(direct);
 expect(await b.getAttribute('data-count')).toBe(count);
 if(qa)await s.screenshot({path:`${qa}/rear-${width}.png`});
 await all.click();await expect(s).toHaveAttribute('data-wires-visible','true');
 await step.click();await expect(b).toHaveAttribute('data-count',String(Number(count)+1));
 await t.selectOption('switch');await expect(s).toHaveAttribute('data-wires','2');
 await expect(s).toHaveAttribute('data-moxa-model','moxa-eds-205a');
 expect((await points()).map(({a,b})=>[a,b])).toEqual([['L.eth','SW.a'],['SW.b','PC.eth']]);
 expect(round((await points())[1].end)).toEqual(expectedEnd);
 if(qa)await s.screenshot({path:`${qa}/switched-${width}.png`});
 await rear.click();await expect(s).toHaveAttribute('data-wires-visible','false');
 await s.locator('canvas').evaluate(c=>c.dispatchEvent(new Event('webglcontextlost',{cancelable:true})));
 await expect(s).toHaveAttribute('data-loaded','false');await expect(s).not.toHaveAccessibleName(/Dell/);await expect(step).toBeEnabled();
 await b.locator('[data-lightudp-retry]').click();await expect(s).toHaveAttribute('data-loaded','true');
 await expect(s).toHaveAttribute('data-focused-device','all');await expect(s.locator('canvas')).toHaveCount(1);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
