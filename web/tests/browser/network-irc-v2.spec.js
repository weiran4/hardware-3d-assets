import {test,expect} from '@playwright/test';
const ircPath='**/models/photo-bench/irc.glb';
for(const width of [1200,390])test(`IRC Switch V2 photo and 8-chassis IRC routes at ${width}`,async({page})=>{
 test.setTimeout(90000);
 await page.setViewportSize({width,height:900});
 let fetches=0;await page.route(ircPath,r=>{fetches++;return r.continue();});
 const root=page.locator('#rtds-three-networks'),stage=root.locator('.network-stage');
 const inspect=root.locator('button[data-gs316-view=irc-front]');
 await page.goto('./#rtds-presentation-27');
 await expect(stage).toHaveAttribute('data-loaded','true');
 await expect(inspect).toBeHidden();expect(fetches).toBe(0);
 await page.evaluate(()=>location.hash='#rtds-presentation-28');
 await expect(stage).toHaveAttribute('data-gbh-channels','1,2,3');
 await expect(inspect).toBeHidden();expect(fetches).toBe(0);
 await page.evaluate(()=>location.hash='#rtds-presentation-30');
 await expect(stage).toHaveAttribute('data-irc-v2','card-1-caps');
 await expect(stage).toHaveAttribute('data-irc-channels','1,2,3,4,5,6,7,8');
 expect(fetches).toBe(1);
 await expect(root.locator('[data-irc-photo]')).toHaveAttribute('href',/IRC_V2_Chassis_and_Cards__28_\.png$/);
 await root.locator('[data-example=correct]').click();
 await expect(stage).toHaveAttribute('data-wires','25');
 const wires=await root.locator('.network-wires li').allTextContents();
 expect(wires.some(w=>w.startsWith('N8.irc1 ↔ IRC.p8'))).toBeTruthy();
 if(width===1200)await stage.screenshot({path:'screenshots/IRC-V2-P30-overview.png'});
 await inspect.focus();await page.keyboard.press('Enter');
 await expect(stage).toHaveAttribute('data-gs316-view','irc-front');
 await expect(stage).toHaveAttribute('aria-label',/IRC Switch V2/);
 await expect(stage.locator('.network-labels button')).toHaveCount(0);
 await expect(root.locator('[data-act=play]')).toBeDisabled();
 await stage.screenshot({path:`screenshots/IRC-V2-P30-${width}.png`});
 await page.evaluate(()=>location.hash='#rtds-presentation-31');
 await expect(stage).toHaveAttribute('data-gs316-view','wiring');
 expect(await root.locator('.network-wires li').allTextContents()).toEqual(wires);
 await root.locator('[data-example=missing]').click();
 await expect(root.locator('[data-result=data]')).toHaveAttribute('data-valid','false');
 await expect(root.locator('[data-result=sync]')).toHaveAttribute('data-valid','true');
});
test('IRC model failure is schematic, and retry retains its existing logical network',async({page})=>{
 await page.route(ircPath,r=>r.abort());
 await page.goto('./#rtds-presentation-30');
 const root=page.locator('#rtds-three-networks'),stage=root.locator('.network-stage');
 await expect(stage).toHaveAttribute('data-irc-v2','schematic');
 await expect(root.locator('button[data-gs316-view=irc-front]')).toBeDisabled();
 await expect(root.locator('[data-irc-fallback]')).toBeVisible();
 await root.locator('[data-example=correct]').click();
 await expect(stage).toHaveAttribute('data-wires','25');
 await expect(root.locator('[data-result=data]')).toHaveAttribute('data-valid','true');
 await page.unroute(ircPath);
 await root.locator('[data-act=irc-retry]').click();
 await expect(stage).toHaveAttribute('data-irc-v2','card-1-caps');
 await expect(stage).toHaveAttribute('data-wires','25');
});
test('abandoned 8-chassis IRC load cannot clear the direct two-chassis lesson',async({page})=>{
 let release,seen;
 const gate=new Promise(resolve=>{release=resolve;});
 const requested=new Promise(resolve=>{seen=resolve;});
 await page.route(ircPath,async route=>{seen();await gate;await route.continue();});
 try{
  await page.goto('./#rtds-presentation-30');await requested;
  await page.evaluate(()=>location.hash='#rtds-presentation-27');
  const stage=page.locator('#rtds-three-networks .network-stage');
  await expect(stage).toHaveAttribute('data-model-count','2');
  const response=page.waitForResponse(r=>r.url().endsWith('/irc.glb'));
  release();await (await response).finished();await page.waitForLoadState('networkidle');
  await expect(stage.locator('canvas')).toHaveCount(1);
  await expect(stage).not.toHaveAttribute('data-irc-v2',/./);
  await expect(stage).toHaveAttribute('data-model-count','2');
 }finally{release();}
});
