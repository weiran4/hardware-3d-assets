import {test,expect} from '@playwright/test';
const hubPath='**/models/photo-bench/gbh.glb.gz';
for(const width of [1200,390])test(`GBH V3 front evidence and unchanged sync wiring at ${width}`,async({page})=>{
 test.setTimeout(90000);
 await page.setViewportSize({width,height:900});
 let loads=0;await page.route(hubPath,r=>{loads++;return r.continue();});
 const root=page.locator('#rtds-three-networks'), stage=root.locator('.network-stage');
 const inspect=root.locator('button[data-gs316-view=gbh-front]');
 await page.goto('./#rtds-presentation-27');await expect(stage).toHaveAttribute('data-loaded','true');
 await expect(inspect).toBeHidden();expect(loads).toBe(0);
 await page.evaluate(()=>location.hash='#rtds-presentation-28');
 await expect(stage).toHaveAttribute('data-gbh-v3','photo-caps');
 await expect(stage).toHaveAttribute('data-gbh-channels','1,2,3');
 await expect(root.locator('[data-gbh-photo]')).toHaveAttribute('href',/GBH-front\.jpg$/);
 await root.locator('[data-example=correct]').click();
 await expect(stage).toHaveAttribute('data-wires','10');
 const original=await root.locator('.network-wires li').allTextContents();
 expect(original).toContain('N3.gbh ↔ GBH.p3 · GBH 同步 · 专用 Global Bus 光缆');
 await inspect.focus();await page.keyboard.press('Enter');
 await expect(stage).toHaveAttribute('data-gs316-view','gbh-front');
 await expect(root.locator('.network-labels button')).toHaveCount(0);
 await expect(root.locator('[data-act=play]')).toBeDisabled();
 await stage.screenshot({path:`screenshots/GBH-V3-P28-${width}.png`});
 await root.locator('button[data-gs316-view=wiring]').click();
 await expect(stage).toHaveAttribute('data-gs316-view','wiring');
 expect(await root.locator('.network-wires li').allTextContents()).toEqual(original);
 await root.locator('[data-example=point]').click();
 await expect(root.locator('[data-result=sync]')).toHaveAttribute('data-valid','false');
 await expect(root.locator('[data-result=data]')).toHaveAttribute('data-valid','true');
 await page.evaluate(()=>location.hash='#rtds-presentation-30');
 await expect(stage).toHaveAttribute('data-gbh-channels','1,2,3,4,5,6,7,8');
 await root.locator('[data-example=correct]').click();
 await expect(stage).toHaveAttribute('data-wires','25');
});
test('unavailable GBH visual model leaves a usable, explicitly schematic sync path',async({page})=>{
 await page.route(hubPath,r=>r.abort());
 await page.goto('./#rtds-presentation-28');
 const root=page.locator('#rtds-three-networks'),stage=root.locator('.network-stage');
 await expect(stage).toHaveAttribute('data-gbh-v3','schematic');
 await expect(stage).toHaveAttribute('data-loaded','true');
 await expect(root.locator('button[data-gs316-view=gbh-front]')).toBeDisabled();
 await expect(root.locator('[data-gbh-fallback]')).toBeVisible();
 await root.locator('[data-example=correct]').click();
 await expect(root.locator('[data-result=sync]')).toHaveAttribute('data-valid','true');
 await expect(stage).toHaveAttribute('data-wires','10');
 await page.unroute(hubPath);
 await root.locator('[data-act=gbh-retry]').click();
 await expect(stage).toHaveAttribute('data-gbh-v3','photo-caps');
 await expect(stage).toHaveAttribute('data-wires','10');
 await expect(root.locator('[data-result=sync]')).toHaveAttribute('data-valid','true');
});
test('abandoned GBH load cannot clear the newer direct scene',async({page})=>{
 let release,requestSeen;
 const gate=new Promise(resolve=>{release=resolve;});
 const requested=new Promise(resolve=>{requestSeen=resolve;});
 await page.route(hubPath,async route=>{requestSeen();await gate;await route.continue();});
 try{
  await page.goto('./#rtds-presentation-28');
  await requested;
  await page.evaluate(()=>location.hash='#rtds-presentation-27');
  const root=page.locator('#rtds-three-networks'),stage=root.locator('.network-stage');
  await expect(stage).toHaveAttribute('data-model-count','2');
  const response=page.waitForResponse(r=>r.url().endsWith('/gbh.glb.gz'));
  release();await (await response).finished();
  await expect(stage).toHaveAttribute('data-loaded','true');
  await expect(stage.locator('canvas')).toHaveCount(1);
  await page.waitForLoadState('networkidle');
  await expect(stage).toHaveAttribute('data-model-count','2');
  await expect(stage).not.toHaveAttribute('data-gbh-v3',/./);
  await root.locator('[data-example=correct]').click();
  await expect(stage).toHaveAttribute('data-wires','5');
 }finally{release();}
});
