import {test,expect} from '@playwright/test';
for(const width of [1200,390])test(`GS316v3 exterior and physical LAN anchors at ${width}px`,async({page})=>{
 test.setTimeout(90000);
 await page.setViewportSize({width,height:900});
 await page.goto('./#rtds-presentation-25');
 const root=page.locator('#rtds-three-networks'),stage=root.locator('.network-stage');
 const view=key=>root.locator('button[data-gs316-view='+key+']');
 await expect(stage).toHaveAttribute('data-loaded','true');
 await expect(stage).toHaveAttribute('data-gs316-mapped-jacks','1,2,3');
 await root.locator('[data-example=correct]').click();
 await expect(stage).toHaveAttribute('data-wires','5');
 const links=await root.locator('.network-wires li').allTextContents();
 await expect(root.locator('a[data-gs316-photo=front]')).toHaveAttribute('href',/gs316v3_wshadow_topfront_image$/);
 await expect(root.locator('a[data-gs316-photo=rear]')).toHaveAttribute('href',/gs316v3_wshadow_backright_image$/);
 for(const key of ['front','rear']){
  await view(key).focus();await page.keyboard.press('Enter');
  await expect(stage).toHaveAttribute('data-gs316-view',key);
  await expect(view(key)).toHaveAttribute('aria-pressed','true');
  await expect(root.locator('.network-labels button')).toHaveCount(0);
  await expect(root.locator('[data-act=play]')).toBeDisabled();
  expect(Number(await stage.getAttribute('data-triangles'))).toBeGreaterThan(1000);
  await stage.screenshot({path:`screenshots/GS316v3-${key}-${width}.png`});
 }
 await view('wiring').click();await expect(stage).toHaveAttribute('data-gs316-view','wiring');
 expect(await root.locator('.network-wires li').allTextContents()).toEqual(links);
 await expect(stage).toHaveAttribute('data-wires','5');
 await expect(root.locator('[data-result=lan]')).toHaveAttribute('data-valid','true');
 await page.evaluate(()=>location.hash='#rtds-presentation-30');
 await expect(stage).toHaveAttribute('data-loaded','true');
 await expect(stage).toHaveAttribute('data-gs316-mapped-jacks','1,2,3,4,5,6,7,8,9');
 await root.locator('[data-example=correct]').click();
 await expect(stage).toHaveAttribute('data-wires','25');
 const terminals=root.locator('[data-param=device]');await terminals.selectOption('LAN');
 await expect(root.locator('.network-ports [data-port="LAN.p8"]')).toHaveText('LAN.p8');
 await expect(root.locator('[data-result=data]')).toHaveAttribute('data-valid','true');
 await root.locator('[data-example=udp]').click();
 await expect(root.locator('[data-result=lan]')).toHaveAttribute('data-valid','false');
 await expect(root.locator('[data-result=sync]')).toHaveAttribute('data-valid','true');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
